#!/usr/bin/env python3
"""
meta-suite packager — builds every non-plugin distribution format into dist/.

    python scripts/package.py           # (re)build dist/
    python scripts/package.py --check   # CI: fail if dist/ is stale vs skills/

Claude Code installs straight from the repo as a plugin and needs none of this. dist/ is for
every other surface (see INSTALL.md for which file goes where):

  dist/upload/<skill>.zip      one skill per zip, folder at the zip root, description swapped for
                               metadata.short-description (<=200 chars, the claude.ai limit).
                               For claude.ai / Claude Desktop, the Claude API, ChatGPT Skills,
                               the OpenAI API, and Grok Skills.
  dist/meta-suite-skills.zip   all nine skill folders, full descriptions — unzip into any agent's
                               skills directory (~/.claude/skills, ~/.agents/skills, ...).
  dist/prompts/<skill>.md      one skill + all its references inlined as a single file — for
                               tools with no skills support (system prompt / knowledge file).
  dist/meta-suite-prompt.md    all nine skills inlined as one knowledge file.
  dist/instructions.md         an under-8,000-char router for ChatGPT Projects / Custom GPTs /
                               Grok Projects, used together with meta-suite-prompt.md.

Stdlib only; zips are byte-for-byte deterministic so --check can diff them.
"""
from __future__ import annotations
import io, re, sys, zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DIST = ROOT / "dist"
SKIP = {"__pycache__", ".DS_Store"}
EPOCH = (1980, 1, 1, 0, 0, 0)
INSTRUCTIONS_LIMIT = 8000


def skill_files(skill: Path) -> list[Path]:
    return sorted(p for p in skill.rglob("*")
                  if p.is_file() and not SKIP.intersection(p.relative_to(skill).parts))


def split(text: str) -> tuple[str, str]:
    _, fm, body = text.split("---", 2)
    return fm, body


def short_description(text: str) -> str:
    m = re.search(r'^\s+short-description:\s*"((?:[^"\\]|\\.)*)"\s*$', split(text)[0], re.M)
    if not m:
        sys.exit("missing metadata.short-description — run scripts/validate.py")
    return m.group(1).replace('\\"', '"').replace("\\\\", "\\")


def with_short_description(text: str) -> str:
    """Swap the long description block for the <=200-char upload-safe one."""
    fm, body = split(text)
    short = short_description(text).replace("\\", "\\\\").replace('"', '\\"')
    fm = re.sub(r"^description:\s*>-?\n(?:[ \t]+.*\n)+", f'description: "{short}"\n', fm, flags=re.M)
    return f"---{fm}---{body}"


def zip_bytes(entries: list[tuple[str, bytes]]) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for name, data in sorted(entries):
            info = zipfile.ZipInfo(name, date_time=EPOCH)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = (0o755 if name.endswith(".py") else 0o644) << 16
            z.writestr(info, data)
    return buf.getvalue()


def inline(skill: Path) -> str:
    """One skill as one Markdown file: SKILL.md, then every supporting file under a path header."""
    name = skill.name
    parts = [f"<!-- meta-suite skill: {name} — generated by scripts/package.py, do not edit -->",
             (skill / "SKILL.md").read_text().strip()]
    for f in skill_files(skill):
        rel = f.relative_to(skill).as_posix()
        if rel == "SKILL.md":
            continue
        fence = "```" + ("python" if f.suffix == ".py" else "xml" if f.suffix == ".xml" else "")
        text = f.read_text().rstrip()
        body = f"{fence}\n{text}\n```" if f.suffix != ".md" else text
        parts.append(f"\n---\n\n### {name}/{rel}\n\n{body}")
    return "\n\n".join(parts) + "\n"


def build() -> dict[str, bytes]:
    out: dict[str, bytes] = {}
    skills = sorted(p.parent for p in ROOT.glob("skills/*/SKILL.md"))
    everything: list[tuple[str, bytes]] = []
    router_rows, bundle = [], []
    for skill in skills:
        name = skill.name
        upload: list[tuple[str, bytes]] = []
        for f in skill_files(skill):
            rel = f"{name}/{f.relative_to(skill).as_posix()}"
            data = f.read_bytes()
            everything.append((rel, data))
            if f.name == "SKILL.md":
                data = with_short_description(data.decode()).encode()
            upload.append((rel, data))
        out[f"upload/{name}.zip"] = zip_bytes(upload)
        text = inline(skill)
        out[f"prompts/{name}.md"] = text.encode()
        bundle.append(f"\n\n# Skill: {name}\n\n{text}")
        router_rows.append(f"- **{name}**: {short_description((skill / 'SKILL.md').read_text())}")
    out["meta-suite-skills.zip"] = zip_bytes(everything)
    out["meta-suite-prompt.md"] = ("<!-- meta-suite: all nine skills in one knowledge file. "
                                   "Generated by scripts/package.py, do not edit. -->\n"
                                   "Each skill starts at a `# Skill: <name>` heading."
                                   + "".join(bundle)).encode()
    instructions = ROUTER.format(rows="\n".join(router_rows)).strip() + "\n"
    if len(instructions) > INSTRUCTIONS_LIMIT:
        sys.exit(f"dist/instructions.md is {len(instructions)} chars (> {INSTRUCTIONS_LIMIT})")
    out["instructions.md"] = instructions.encode()
    return out


ROUTER = """
You have the meta-suite: nine task-agnostic meta-skills. Their full procedures are in the attached
knowledge file meta-suite-prompt.md, each under a "# Skill: <name>" heading. Each skill works one
level up: instead of doing a single task, it emits the reusable structure that solves the whole
category the task belongs to, then applies it to the task at hand.

When a request matches a skill below (or the user names it, e.g. "meta-review this"), open that
skill's section in meta-suite-prompt.md and follow it step by step, including its references. Do not
improvise from these one-line summaries; the procedure lives in the file.

{rows}

Doctrine for every skill:
- Never ask the user clarifying questions. Infer what you need, state your assumptions in one line,
  and proceed.
- Clear over clever. Give plain, usable output; keep the formal machinery hidden unless asked.
- Leave something reusable behind (a lesson, a template, a knowledge atom) when the skill calls for it.
- If a step needs a capability you lack here (running a script, spawning sub-agents, browsing),
  do that step by hand or say in one line that it was skipped. Never block on it.
"""


def main() -> int:
    built = build()
    if "--check" in sys.argv:
        on_disk = {p.relative_to(DIST).as_posix(): p.read_bytes()
                   for p in DIST.rglob("*") if p.is_file()} if DIST.exists() else {}
        stale = sorted(k for k in built.keys() | on_disk.keys() if built.get(k) != on_disk.get(k))
        for k in stale:
            print(f"  ✗ dist/{k} is stale or unexpected")
        print(f"package.py --check: {len(built)} files, {len(stale)} stale"
              + (" — run: python scripts/package.py" if stale else ""))
        return 1 if stale else 0
    for p in sorted(DIST.rglob("*"), reverse=True) if DIST.exists() else []:
        p.unlink() if p.is_file() else p.rmdir()
    for rel, data in built.items():
        (DIST / rel).parent.mkdir(parents=True, exist_ok=True)
        (DIST / rel).write_bytes(data)
    print(f"package.py: wrote {len(built)} files to dist/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
